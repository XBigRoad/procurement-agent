"""Read business records with original values and verifiable source locations.

Only headers are normalized here. Numeric, date, tax and procurement semantics
belong to the engine. A malformed populated table row remains reviewable, while
ambiguous headers and structurally invalid files raise an actionable ValueError.
"""

