_RESERVED = frozenset({"quote_id", "_source", "_evidence", "_input_issues", "_reviewed_fields"})
_MAX_HEADER_ROW = 31  # A header may follow as many as 30 leading rows.


def _normalized_header(value: str) -> str:
    return re.sub(r"[\s-]+", "_", unicodedata.normalize("NFKC", value).strip()).casefold()


_ALIASES = {
    _normalized_header(alias): field
    for field, aliases in _FIELD_ALIASES.items()
    for alias in (field, *aliases)
}


def _blank(value: Any) -> bool:
    # Zero, False and empty structured business values are populated inputs.
    return value is None or isinstance(value, str) and not value.strip()


def _check_reserved(key: str, location: str) -> None:
    if _normalized_header(key) in _RESERVED:
        raise ValueError(
            f"{location}: reserved metadata field {key!r}; remove it from the input. "
            "Source metadata and quote_id are generated by the reader."
        )


def _headers(
    values: list[Any], location: str, *, require_known: bool = True
) -> list[str | None]:
    names: list[str | None] = []
    seen: dict[str, int] = {}
    for column, value in enumerate(values, 1):
        if _blank(value):
            names.append(None)
            continue
        if not isinstance(value, str) or value.lstrip().startswith("="):
            raise ValueError(f"{location}, column {column}: use a textual business field header.")
        _check_reserved(value, location)
        name = _ALIASES.get(_normalized_header(value), value)
        if name in seen:
            raise ValueError(
                f"{location}: duplicate canonical header {name!r} in columns "
                f"{seen[name]} and {column}; keep one column per field."
            )
        seen[name] = column
        names.append(name)
    if require_known and not any(name in _FIELD_ALIASES for name in names):
        raise ValueError(
            f"{location}: no recognized table header; use fields such as "
            "supplier/供应商, item_id/物料编码, or price."
        )
    return names


def _new_record(source: dict[str, Any]) -> dict[str, Any]:
    # The path and input kind deliberately do not affect identity: loading an
    # identical copy twice must not manufacture independent supplier offers.
    identity = [
        source["sha256"], source["format"], source.get("sheet"),
        source.get("row"), source.get("json_pointer"),
    ]
    encoded = json.dumps(identity, ensure_ascii=True, separators=(",", ":")).encode("utf-8")
    return {
        "quote_id": "q_" + hashlib.sha256(encoded).hexdigest(),
        "_source": deepcopy(source),
        "_evidence": {},
        "_input_issues": [],
    }


def _issue(record: dict[str, Any], code: str, field: str, message: str) -> None:
    record["_input_issues"].append({"code": code, "field": field, "message": message})


def _add_value(
    record: dict[str, Any], name: str, value: Any, evidence: dict[str, Any],
    *, formula: bool = False, cell_error: bool = False,
) -> None:
    record[name] = deepcopy(value)
    evidence = {**deepcopy(evidence), "raw_value": deepcopy(value)}
    formula = formula or isinstance(value, str) and value.lstrip().startswith("=")
    if formula:
        evidence["formula"] = deepcopy(value)
        _issue(record, "formula", name, "Formula input requires an explicitly reviewed literal value.")
    if cell_error:
        _issue(record, "cell_error", name, "Excel error value requires review against the original cell.")
    record["_evidence"][name] = evidence


def _check_populated_record(record: dict[str, Any]) -> None:
    if not any(name in record and not _blank(record[name]) for name in _FIELD_ALIASES):
        _issue(
            record, "malformed_row", "",
            "Populated row has no populated recognized business field; review its headers and values.",
        )


def _table_record(
    names: list[str | None], raw_headers: list[Any], values: list[Any],
    source: dict[str, Any], *, formulas: set[int] | None = None,
    errors: set[int] | None = None,
) -> dict[str, Any] | None:
    if all(_blank(value) for value in values):
        return None
    record = _new_record(source)
    used_names = set(name for name in names if name is not None)
    if source["format"] == "csv" and len(values) != len(names):
        _issue(
            record, "malformed_row", "",
            f"CSV row supplies {len(values)} columns for {len(names)} headers; review the original row.",
        )
    for index, value in enumerate(values):
        name = names[index] if index < len(names) else None
        raw_header = raw_headers[index] if index < len(raw_headers) else None
        if name is None:
            if _blank(value):
                continue
            name = f"unmapped_column_{index + 1}"
            while name in used_names:
                name += "_"
            used_names.add(name)
            _issue(
                record, "missing_header", name,
                f"Populated column {index + 1} has no header; assign a business field name.",
            )
        evidence = {**source, "column": index + 1, "raw_header": raw_header}
        if source["format"] == "xlsx":
            evidence["cell"] = f"{get_column_letter(index + 1)}{source['row']}"
        _add_value(
            record, name, value, evidence,
            formula=index in (formulas or ()), cell_error=index in (errors or ()),
        )
    _check_populated_record(record)
    return record


def _read_csv(content: bytes, source: dict[str, Any]) -> list[dict]:
    try:
        text = content.decode("utf-8-sig")
    except UnicodeDecodeError:
        try:
            text = content.decode("gb18030")
        except UnicodeDecodeError as exc:
            raise ValueError("CSV cannot be decoded; save it as UTF-8 or GB18030.") from exc
    if "\x00" in text:
        raise ValueError("CSV contains NUL bytes; export a text CSV in UTF-8 or GB18030.")
    reader = csv.reader(io.StringIO(text, newline=""), strict=True)
    records: list[dict] = []
    names = None
    raw_headers: list[Any] = []
    try:
        while True:
            start_line = reader.line_num + 1
            try:
                values = next(reader)
            except StopIteration:
                break
            if names is None:
                if all(_blank(value) for value in values):
                    continue
                raw_headers = values
                names = _headers(values, f"CSV header at line {start_line}")
                continue
            row_source = {**source, "row": start_line}
            if reader.line_num != start_line:
                row_source["row_end"] = reader.line_num
            record = _table_record(names, raw_headers, values, row_source)
            if record is not None:
                records.append(record)
    except csv.Error as exc:
        raise ValueError(
            f"Invalid CSV near physical line {reader.line_num}: {exc}; check quoting and delimiters."
        ) from exc
    return records


def _excel_value(cell: Any) -> Any:
    value = cell.value
    if isinstance(value, ArrayFormula):
        return value.text if value.text is not None else dict(value)
    if isinstance(value, DataTableFormula):
        return dict(value)
    return value


def _xlsx_header(preview: list[tuple[int, tuple]]) -> int | None:
    """Prefer a multi-field table header to a leading field/value cover row.

    One-column tables and tables with one known field plus custom columns remain
    valid. The latter are a fallback when the preview contains no fuller header.
    Validation of the selected row still rejects duplicate and reserved fields.
    """
    fallback = None
    for index, (_, cells) in enumerate(preview):
        values = [_excel_value(cell) for cell in cells]
        labels = [_normalized_header(value) for value in values if isinstance(value, str)]
        recognized = sum(label in _ALIASES for label in labels)
        if any(label in _RESERVED for label in labels):
            return index
        if recognized >= 2:
            return index
        if recognized and fallback is None:
            if sum(not _blank(value) for value in values) == 1:
                return index
            fallback = index
    return fallback


def _read_xlsx(content: bytes, source: dict[str, Any]) -> list[dict]:
    records: list[dict] = []
    with io.BytesIO(content) as stream:
        workbook = load_workbook(stream, read_only=True, data_only=False, keep_links=False)
        try:
            for sheet in workbook.worksheets:
                # Producers sometimes write an incorrect used-range dimension.
                # Read the actual sheet XML so that rows cannot silently disappear.
                sheet.reset_dimensions()
                rows = enumerate(sheet.iter_rows(), 1)
                preview = list(islice(rows, _MAX_HEADER_ROW))
                header_index = _xlsx_header(preview)
                if header_index is None:
                    populated = any(
                        any(not _blank(_excel_value(cell)) for cell in cells)
                        for _, cells in chain(preview, rows)
                    )
                    if not populated:
                        continue
                    raise ValueError(
                        f"XLSX sheet {sheet.title!r}: no recognized header in rows 1–{_MAX_HEADER_ROW}; "
                        "place a business table header after at most 30 leading rows."
                    )
                header_row, header_cells = preview[header_index]
                raw_headers = [_excel_value(cell) for cell in header_cells]
                names = _headers(raw_headers, f"XLSX sheet {sheet.title!r}, header row {header_row}")
                for row_number, cells in chain(preview[header_index + 1:], rows):
                    values = [_excel_value(cell) for cell in cells]
                    record = _table_record(
                        names, raw_headers, values,
                        {**source, "sheet": sheet.title, "row": row_number},
                        formulas={i for i, cell in enumerate(cells) if cell.data_type == "f"},
                        errors={i for i, cell in enumerate(cells) if cell.data_type == "e"},
                    )
                    if record is not None:
                        records.append(record)
        finally:
            workbook.close()
    return records


def _unique_json_object(pairs: list[tuple[str, Any]]) -> dict[str, Any]:
    result: dict[str, Any] = {}
    for key, value in pairs:
        if key in result:
            raise ValueError(f"Duplicate JSON key {key!r}; keep one value per property.")
        result[key] = value
    return result


def _reject_json_constant(value: str) -> None:
    raise ValueError(f"Invalid JSON constant {value!r}; use a JSON number, null, or an explicit string.")


def _pointer_token(value: str) -> str:
    return value.replace("~", "~0").replace("/", "~1")


def _json_record(raw: dict[str, Any], source: dict[str, Any]) -> dict[str, Any] | None:
    keys = list(raw)
    location = f"JSON object at {source['json_pointer'] or '/ (root)'}"
    names = _headers(keys, location, require_known=False)
    if any(name is None for name in names):
        raise ValueError(f"{location}: empty field name; give every property a business field name.")
    if all(_blank(value) for value in raw.values()):
        return None
    record = _new_record(source)
    for key, name in zip(keys, names):
        evidence = {
            **source, "json_pointer": source["json_pointer"] + "/" + _pointer_token(key),
            "raw_header": key,
        }
        _add_value(record, name, raw[key], evidence)
    _check_populated_record(record)
    return record


def _read_json(content: bytes, source: dict[str, Any]) -> list[dict]:
    try:
        payload = json.loads(
            content.decode("utf-8-sig"), object_pairs_hook=_unique_json_object,
            parse_constant=_reject_json_constant,
        )
    except UnicodeDecodeError as exc:
        raise ValueError("JSON cannot be decoded; save the file as UTF-8.") from exc
    except json.JSONDecodeError as exc:
        raise ValueError(
            f"Invalid JSON at line {exc.lineno}, column {exc.colno}: {exc.msg}."
        ) from exc
    wrapper = None
    if isinstance(payload, dict):
        for key in payload:
            _check_reserved(key, "JSON root")
        wrappers = [key for key in ("quotes", "records", "prices") if key in payload]
        if len(wrappers) > 1:
            raise ValueError("JSON has multiple record wrappers; use exactly one of quotes, records, prices.")
        if wrappers:
            wrapper = wrappers[0]
            if len(payload) != 1:
                raise ValueError(
                    f"JSON wrapper {wrapper!r} has additional fields; place business fields inside each record."
                )
            payload = payload[wrapper]
            if not isinstance(payload, list):
                raise ValueError(f"JSON wrapper {wrapper!r} must contain an array.")
        else:
            record = _json_record(payload, {**source, "json_pointer": ""})
            return [record] if record is not None else []
    if not isinstance(payload, list):
        raise ValueError("JSON must contain an object, an array of objects, or a quotes/records/prices wrapper.")
    records: list[dict] = []
    for index, raw in enumerate(payload):
        pointer = f"/{wrapper}/{index}" if wrapper else f"/{index}"
        row_source = {**source, "json_pointer": pointer}
        if wrapper == "prices":
            if isinstance(raw, bool) or not isinstance(raw, (int, float)):
                raise ValueError(f"JSON {pointer}: legacy prices entries must be numbers.")
            record = _new_record(row_source)
            _add_value(record, "price", raw, row_source)
        else:
            if not isinstance(raw, dict):
                raise ValueError(f"JSON {pointer}: each record must be an object.")
            record = _json_record(raw, row_source)
        if record is not None:
            records.append(record)
    return records


def load_records(path: Path, kind: str = "quotes") -> list[dict]:
    """Load quotes/history/market records without coercing business values.

    Empty inputs return no records. Ambiguous file structures fail atomically;
    populated irregular table rows and formulas retain their evidence and issues.
    Identical file bytes and source positions yield identical quote IDs even when
    a file is copied or loaded in another input role.
    """
    if kind not in ("quotes", "history", "market"):
        raise ValueError(f"Unsupported input kind {kind!r}; use quotes, history, or market.")
    path = Path(path)
    readers = {".csv": _read_csv, ".xlsx": _read_xlsx, ".json": _read_json}
    suffix = path.suffix.lower()
    if suffix not in readers:
        raise ValueError(f"Unsupported input format {suffix!r} for {path}; use .csv, .xlsx, or .json.")
    try:
        content = path.read_bytes()
    except OSError as exc:
        raise ValueError(f"Cannot read input file {path}: {exc}. Check the path and read permissions.") from exc
    source = {"file": str(path.resolve()), "sha256": hashlib.sha256(content).hexdigest(), "format": suffix[1:]}
    try:
        return readers[suffix](content, source)
    except (
        ValueError, BadZipFile, InvalidFileException, OSError, EOFError,
        KeyError, TypeError, IndexError, SyntaxError, OverflowError, RuntimeError, ZlibError,
    ) as exc:
        raise ValueError(f"Cannot ingest {path} ({suffix[1:]}): {exc}") from exc
